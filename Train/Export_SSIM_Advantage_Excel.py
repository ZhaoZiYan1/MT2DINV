# -*- coding: utf-8 -*-
"""
Export an Excel workbook ranking Mamba's SSIM advantage using saved per-sample
SSIM results (.mat) from three networks.
================================================================
Input: ../Result/SSIM_Comparison_3Networks.mat (generated by SSIM_Distribution_Plot.py,
       containing ssim_Mamba / ssim_Trans / ssim_UNet / sample_idx)
Output: ../Result/SSIM_Mamba_Advantage_Ranked_1000.xlsx
        - Sheet "Ranked_All_1000": All samples ranked by Mamba's advantage
          (min_margin) in descending order, with columns:
          rank, sample_idx, ssim_mamba, ssim_trans, ssim_unet,
          margin_vs_trans, margin_vs_unet, min_margin, is_superior
        - Sheet "Summary": SSIM statistics for each network, Mamba's win rates,
          and the number of samples showing a substantial advantage.
Definition of advantage (consistent with SSIM_Distribution_Plot.py):
        margin_vs_X = SSIM_Mamba - SSIM_X;
        min_margin  = min(margin_vs_trans, margin_vs_unet)  # Positive only if Mamba outperforms both networks
        is_superior = min_margin >= MARGIN_THRESHOLD (default: 0.02)
Note: sample_idx uses zero-based indexing and can be passed directly to
      python Mamba_MT2D_Predicted.py --samples <idx ...> to generate comparison figures in batches.
"""
import os
import numpy as np
import pandas as pd
from scipy.io import loadmat

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MAT_PATH = os.path.join(ROOT, "Result", "SSIM_Comparison_3Networks.mat")
XLSX_PATH = os.path.join(ROOT, "Result", "SSIM_Mamba_Advantage_Ranked_1000.xlsx")
MARGIN_THRESHOLD = 0.02          # Same decision threshold as in SSIM_Distribution_Plot.py

# ---- Read per-sample SSIM values ----
if not os.path.isfile(MAT_PATH):
    raise FileNotFoundError(f"File not found: {MAT_PATH}. Please run SSIM_Distribution_Plot.py first.")
m = loadmat(MAT_PATH)
s_m = np.asarray(m['ssim_Mamba'], dtype=np.float64).ravel()
s_t = np.asarray(m['ssim_Trans'], dtype=np.float64).ravel()
s_u = np.asarray(m['ssim_UNet'], dtype=np.float64).ravel()
n = s_m.size
if not (s_t.size == s_u.size == n):
    raise ValueError(f"Inconsistent sample counts across the three networks: Mamba={n}, Trans={s_t.size}, UNet={s_u.size}")
print(f"Loaded: {MAT_PATH} (n={n})")

# ---- Compute advantage margins and rank all samples by descending min_margin ----
m_t, m_u = s_m - s_t, s_m - s_u
min_margin = np.minimum(m_t, m_u)
superior = min_margin >= MARGIN_THRESHOLD
rank_all = np.argsort(-min_margin, kind='stable')

df_rank = pd.DataFrame({
    'rank':            np.arange(1, n + 1),
    'sample_idx':      rank_all,
    'ssim_mamba':      s_m[rank_all],
    'ssim_trans':      s_t[rank_all],
    'ssim_unet':       s_u[rank_all],
    'margin_vs_trans': m_t[rank_all],
    'margin_vs_unet':  m_u[rank_all],
    'min_margin':      min_margin[rank_all],
    'is_superior':     superior[rank_all]})

# ---- Summary sheet ----
rows = []
for name, s in [('Mamba', s_m), ('Transformer', s_t), ('UNet', s_u)]:
    rows.append({'network': name, 'ssim_mean': s.mean(), 'ssim_std': s.std(),
                 'ssim_median': float(np.median(s)), 'ssim_min': s.min(), 'ssim_max': s.max()})
df_sum = pd.DataFrame(rows)
extra = pd.DataFrame([
    {'network': 'Mamba win rate vs Transformer (%)', 'ssim_mean': 100.0 * (m_t > 0).mean()},
    {'network': 'Mamba win rate vs UNet (%)',        'ssim_mean': 100.0 * (m_u > 0).mean()},
    {'network': f'superior count (thr={MARGIN_THRESHOLD})', 'ssim_mean': int(superior.sum())},
    {'network': 'n_samples', 'ssim_mean': n}])
df_sum = pd.concat([df_sum, extra], ignore_index=True)

# ---- Write Excel workbook ----
with pd.ExcelWriter(XLSX_PATH, engine='openpyxl') as writer:
    df_rank.to_excel(writer, sheet_name='Ranked_All_1000', index=False)
    df_sum.to_excel(writer, sheet_name='Summary', index=False)
print(f"Excel saved: {XLSX_PATH}")

# ---- Console preview ----
print(f"\nTop 10 samples with the largest Mamba advantage (descending min_margin; {n} samples in total, "
      f"including {int(superior.sum())} samples with a substantial advantage):")
print(df_rank.head(10).to_string(index=False,
      formatters={c: '{:.6f}'.format for c in df_rank.columns if df_rank[c].dtype == float}))
print("\nSummary:")
print(df_sum.to_string(index=False))
