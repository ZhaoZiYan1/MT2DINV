"""
MT2D field-data noise generator (two TM channels, random 0-5% Gaussian noise in the linear domain, sample-specific noise levels)
================================================================
Features:
    Add Gaussian noise to two TM observation channels (Rhoyx, Phsyx) in the clean
    Train / Validate / Test .mat datasets with field-data geometry (32x32/Fre21/Obs21),
    generating new noisy datasets. Field-data training and inversion use TM mode only;
    TE channels are neither perturbed nor saved. The sig_k ground truth and all other fields remain unchanged.

Noise model (apparent resistivity and phase use different perturbations linked by eps):
    eps = relative error (1 sigma) of apparent resistivity in the linear domain; independently drawn
          for each sample from U(eps_min, eps_max). Apparent resistivity: multiplicative Gaussian noise
            rho_noisy = rho * (1 + eps * N(0,1))    # multiplicative relative 1 sigma = eps
      - Phase: additive Gaussian noise in degrees, with amplitude physically linked to eps:
            rho = |Z|^2; relative rho error eps corresponds to relative Z error of approximately eps/2;
            phase perturbation (rad) ≈ relative Z error -> sigma_p = (eps/2) * 180/pi (deg)
            phs_noisy = phs + sigma_p * N(0,1)
        (Example: eps=5% -> multiplicative rho 1 sigma=5%, sigma_phase=1.43 degrees; typical field phase noise 1-5 degrees.)
    Independent noise realizations are drawn for each (sample, frequency, observed station).
Random number stream (fully reproducible):
    Each split uses a separately initialized np.random.default_rng(seed), with a fixed draw order:
    (1) eps for all samples -> (2) Rhoyx -> (3) Phsyx
    Thus generating a split alone or together with all three splits yields identical values;
    with the same seed, Mamba/Trans/UNet use identical noise realizations for paired comparisons.
Outputs (default slim mode: only TM training fields plus freq/obs for traceability):
    Train_MT2D_32x32_Fre21_Obs21_10000_Noise0-5%.mat    (~115MB)
    Validate_MT2D_32x32_Fre21_Obs21_1000_Noise0-5%.mat  (~12MB)
    Test_MT2D_32x32_Fre21_Obs21_1000_Noise0-5%.mat      (~12MB)
    Test_..._NoiseCompare_Sample{k}.png    Clean/noisy pseudosection comparison for a selected sample
Usage examples:
    python Generate_Noisy_Dataset.py                          # Generate all three datasets; default U(0,5%), seed=123
    python Generate_Noisy_Dataset.py --splits test            # Generate the test set only
    python Generate_Noisy_Dataset.py --eps-mode fixed --eps 0.05   # Fixed 5% noise level (for degradation curves)
    python Generate_Noisy_Dataset.py --plot-sample 7          # Also plot the comparison for sample 7
    python Generate_Noisy_Dataset.py --plot-only --plot-sample 7  # Plot sample 7 without regenerating datasets
Prerequisite: clean datasets must first be generated by MT2D_Model_Feild.py (forward modeling 10,000 training samples can be time-consuming).
"""
import argparse
import os
import time
import numpy as np
import scipy.io
# ==================================================
# Configuration
# ==================================================
HERE = os.path.dirname(os.path.abspath(__file__))
# Three source datasets (split -> filename; field geometry 32x32/Fre21/Obs21; generated by MT2D_Model_Feild.py)
SOURCE_FILES = {
    'train': 'Train_MT2D_32x32_Fre21_Obs21_10000.mat',
    'validate': 'Validate_MT2D_32x32_Fre21_Obs21_1000.mat',
    'test': 'Test_MT2D_32x32_Fre21_Obs21_1000.mat',
}
SPLIT_ORDER = ['train', 'validate', 'test']

# Field training/inversion uses TM mode only: perturb the two TM channels; do not perturb or save TE channels.
# Two observed channels (noise is applied only to these fields, in random draw order).
RHO_CHANNELS = ['Rhoyx']            # TM apparent resistivity -> multiplicative Gaussian noise in the linear domain (relative 1 sigma = eps)
PHS_CHANNELS = ['Phsyx']            # TM phase -> additive Gaussian noise (degrees)
NOISE_FIELD_ORDER = ['Rhoyx', 'Phsyx']

# Fields retained in slim mode (noisy TM channels + ground truth + coordinate metadata).
SLIM_FIELDS = NOISE_FIELD_ORDER + ['sig_k', 'freq', 'obs']
# ==================================================
# Noise model
# ==================================================
def sigma_phase_from_eps(eps):
    """Phase noise standard deviation (degrees), physically linked to the relative
    apparent-resistivity error eps: rho = |Z|^2; relative rho error eps corresponds to
    relative Z error eps/2 and phase perturbation (rad) ≈ eps/2. Input eps can be a scalar or (N,1,1) array; output has the same shape."""
    return np.degrees(0.5 * np.asarray(eps, dtype=np.float64))
def draw_eps(rng, n_samples, eps_mode, eps_fixed, eps_min, eps_max):
    # One eps value per sample, shared across frequencies/stations; noise draws are elementwise independent.
    if eps_mode == 'uniform':
        return rng.uniform(eps_min, eps_max, size=(n_samples, 1, 1))
    return np.full((n_samples, 1, 1), eps_fixed, dtype=np.float64)
def add_noise(raw, eps_arr, rng):
    """Apply noise to the two TM channels in a fixed order; return {field: noisy array}.
    Apparent resistivity: multiplicative in the linear domain (relative 1 sigma = eps); phase: additive in degrees (sigma = eps/2 rad)."""
    s_p = sigma_phase_from_eps(eps_arr)
    noisy = {}
    for k in NOISE_FIELD_ORDER:
        n = rng.standard_normal(raw[k].shape)   # Independent standard-normal draw for each element
        if k in RHO_CHANNELS:
            noisy[k] = raw[k] * (1.0 + eps_arr * n)
        else:
            noisy[k] = raw[k] + s_p * n
    return noisy
# ==================================================
# Verification
# ==================================================
def verify_split(raw, noisy, mdict, eps_arr):
    """Compare empirical and theoretical noise statistics; saved sig_k must exactly match the source."""
    s_p = sigma_phase_from_eps(eps_arr)
    eps = np.asarray(eps_arr, dtype=np.float64)
    # Theoretical pooled standard deviations under varying eps: rho relative residual = sqrt(E[eps^2]); phase = sqrt(E[sigma_p^2]).
    theo_r = float(np.sqrt(np.mean(eps ** 2)))
    theo_p = float(np.sqrt(np.mean(s_p ** 2)))
    print(f" eps distribution: min={eps_arr.min():.4f} mean={eps_arr.mean():.4f} max={eps_arr.max():.4f}")
    print(f" Theoretical pooled std: relative rho residual={theo_r:.4f} ({theo_r * 100:.2f}%), sigma_phase={theo_p:.2f} deg")
    stats = {'theo_sigma_rho_relative': theo_r, 'theo_sigma_phase_deg': theo_p, 'channels': {}}
    for k in NOISE_FIELD_ORDER:
        if k in RHO_CHANNELS:
            resid = (noisy[k] - raw[k]) / raw[k]   # Relative residual in the linear domain
            emp = float(resid.std())
            label = 'relative rho residual std'
        else:
            resid = noisy[k] - raw[k]
            emp = float(resid.std())
            label = 'phase residual std (deg)'
        ref = theo_r if k in RHO_CHANNELS else theo_p
        dev = 100.0 * abs(emp - ref) / ref
        print(f"    {k:6s}: {label}={emp:.4f} (theoretical {ref:.4f}, deviation {dev:.2f}%)")
        stats['channels'][k] = {'empirical_std': emp, 'theoretical_std': ref}
    if 'sig_k' in mdict:
        # Final check that saved sig_k is elementwise identical to the original source data.
        stats['sig_k_untouched'] = bool(np.array_equal(mdict['sig_k'], raw['sig_k']))
        print(f"    sig_k unchanged (elementwise identical to source): {stats['sig_k_untouched']}")
    return stats

# ==================================================
# Comparison plots: clean vs noisy TM-channel pseudosections for a selected sample
# ==================================================
def plot_sample_compare(out_path, raw, noisy, eps_arr, sample_idx):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    freq = raw['freq'].squeeze()      # Frequency values (original comment: 31, descending, index 0 = 1000 Hz)
    obs_km = raw['obs'].squeeze() / 1000.0   # Observed station positions along the profile (km)
    eps_i = float(eps_arr[sample_idx, 0, 0])
    s_p = sigma_phase_from_eps(eps_i)
    rows = [('Rhoyx', True, 'TM apparent resistivity log10(rho)'),
            ('Phsyx', False, 'TM phase phi_yx (deg)')]
    fig, axes = plt.subplots(2, 2, figsize=(13, 8), constrained_layout=True)
    for r, (key, use_log, title) in enumerate(rows):
        clean = np.log10(raw[key][sample_idx]) if use_log else raw[key][sample_idx]
        noisv = np.log10(noisy[key][sample_idx]) if use_log else noisy[key][sample_idx]
        vmin, vmax = min(clean.min(), noisv.min()), max(clean.max(), noisv.max())
        for c, (data, tag) in enumerate([(clean, 'clean'), (noisv, 'noisy')]):
            ax = axes[r, c]
            pcm = ax.pcolormesh(obs_km, freq, data, shading='auto', cmap='jet', vmin=vmin, vmax=vmax)
            ax.set_yscale('log')
            ax.set_ylabel('Frequency (Hz)' if c == 0 else '')
            ax.set_xlabel('Distance (km)')
            ax.set_title(f'{title} - {tag}', fontsize=10)
            fig.colorbar(pcm, ax=ax, pad=0.02)
    fig.suptitle(f'Sample {sample_idx} | eps={eps_i:.4f}  ->  '
                 f'rho linear multiplicative noise 1-sigma = {eps_i * 100:.1f}%,  '
                 f'sigma_phase={float(s_p):.2f} deg', fontsize=12, fontweight='bold')
    png = out_path.replace('.mat', f'_NoiseCompare_Sample{sample_idx}.png')
    fig.savefig(png, dpi=200)
    plt.close(fig)
    print(f"    Comparison plot saved: {png}")
    return png
# ==================================================
# Main workflow
# ==================================================
def build_output_name(src_name, eps_mode, eps_fixed, eps_min, eps_max):
    # uniform: Noise{lower%}-{upper%} (e.g., Noise0-10%); fixed: Noise{level%} (e.g., Noise5%).
    if eps_mode == 'uniform':
        tag = f'Noise{eps_min * 100:g}-{eps_max * 100:g}%'
    else:
        tag = f'Noise{eps_fixed * 100:g}%'
    stem, _ = os.path.splitext(src_name)
    return f'{stem}_{tag}.mat'


def main():
    parser = argparse.ArgumentParser(description='MT2D field-data noise generator (two TM channels, random 0-5% Gaussian noise)')
    parser.add_argument('--splits', nargs='+', default=SPLIT_ORDER,
                        choices=SPLIT_ORDER, help='Dataset splits to generate (default: all three)')
    parser.add_argument('--eps-mode', default='uniform', choices=['uniform', 'fixed'],
                        help="uniform=samplewise eps~U(eps_min,eps_max); fixed=constant noise level")
    parser.add_argument('--eps-min', type=float, default=0.0)
    parser.add_argument('--eps-max', type=float, default=0.05,
                        help='Upper noise limit (default 0.05, i.e., 0-5%%); specify another value if needed, e.g., --eps-max 0.10')
    parser.add_argument('--eps', type=float, default=0.05, help='Noise level in fixed mode (e.g., 0.025/0.05)')
    parser.add_argument('--seed', type=int, default=123)
    parser.add_argument('--keep-fields', default='slim', choices=['slim', 'full'],
                        help='slim=only field TM channels plus freq/obs (recommended); full=copy all fields (TE channels remain clean)')
    parser.add_argument('--overwrite', action='store_true', help='Overwrite existing output files')
    parser.add_argument('--plot-sample', type=int, default=None,
                        help='Generate clean/noisy TM-channel pseudosection plots for the selected sample')
    parser.add_argument('--plot-split', default='test', choices=SPLIT_ORDER,
                        help='Dataset split used for plotting (default: test)')
    parser.add_argument('--plot-only', action='store_true',
                        help='Plot from an existing noisy dataset without regenerating data (requires --plot-sample; '
                             'eps-mode/eps-min/eps-max must match generation settings to locate the file; '
                             'seed must match to reconstruct eps exactly)')
    args = parser.parse_args()

    # ---- Plot-only mode: read existing noisy dataset without regenerating it ----
    if args.plot_only:
        if args.plot_sample is None:
            parser.error('--plot-only must also specify --plot-sample N')
        split = args.plot_split
        out_name = build_output_name(SOURCE_FILES[split], args.eps_mode, args.eps,
                                     args.eps_min, args.eps_max)
        out_path = os.path.join(HERE, out_name)
        if not os.path.isfile(out_path):
            print(f'Noisy dataset not found: {out_name}')
            print('Generate the dataset first, or verify that --eps-mode/--eps-max/--seed match the generation settings')
            return
        print(f'[plot-only] Reading: {out_name}')
        raw = scipy.io.loadmat(os.path.join(HERE, SOURCE_FILES[split]))
        noisy_mat = scipy.io.loadmat(out_path)
        n_samples = raw['Rhoxy'].shape[0]
        if not (0 <= args.plot_sample < n_samples):
            print(f'Sample index {args.plot_sample} is out of range 0-{n_samples - 1}')
            return
        # Reconstruct eps from current arguments and seed, then cross-check against empirical residual estimates.
        rng = np.random.default_rng(args.seed)
        eps_arr = draw_eps(rng, n_samples, args.eps_mode, args.eps, args.eps_min, args.eps_max)
        r1 = (noisy_mat['Rhoyx'] - raw['Rhoyx']) / raw['Rhoyx']
        eps_emp = r1.std(axis=(1, 2)).reshape(n_samples, 1, 1)   # Field TM version has only one rho channel: Rhoyx
        k = args.plot_sample
        eps_exact, eps_est = float(eps_arr[k, 0, 0]), float(eps_emp[k, 0, 0])
        if abs(eps_exact - eps_est) > 0.05 * max(eps_est, 1e-6):
            print(f'[plot-only] Reconstructed eps={eps_exact:.4f} differs substantially from residual estimate {eps_est:.4f}; '
                  f'using residual estimate instead (generation settings may differ)')
            eps_arr = eps_emp
        else:
            print(f'[plot-only] eps reconstructed from seed: sample {k} eps={eps_exact:.4f} '
                  f'(residual cross-check {eps_est:.4f}, consistent)')
        noisy = {kk: noisy_mat[kk] for kk in NOISE_FIELD_ORDER}
        plot_sample_compare(out_path, raw, noisy, eps_arr, args.plot_sample)
        return
    for split in args.splits:
        src = os.path.join(HERE, SOURCE_FILES[split])
        out_name = build_output_name(SOURCE_FILES[split], args.eps_mode, args.eps, args.eps_min, args.eps_max)
        out_path = os.path.join(HERE, out_name)
        print('=' * 72)
        print(f'[{split}] Source file: {SOURCE_FILES[split]}')
        print(f'[{split}] Output file: {out_name}')
        if not os.path.isfile(src):
            print(f'[{split}] Source file not found: {src}')
            print(f'[{split}] Run MT2D_Model_Feild.py first to generate the field-geometry dataset (forward modeling 10,000 training samples can take considerable time)')
            continue
        if os.path.isfile(out_path) and not args.overwrite:
            print(f'[{split}] Output exists and --overwrite was not specified; skipping')
            continue
        t0 = time.time()
        print(f'[{split}] Reading source data...')
        raw = scipy.io.loadmat(src)
        n_samples = raw['Rhoxy'].shape[0]
        print(f'[{split}] Samples: {n_samples}, adding noise (mode={args.eps_mode})...')
        rng = np.random.default_rng(args.seed)   # Reinitialize independently for each split, ensuring consistent standalone generation
        eps_arr = draw_eps(rng, n_samples, args.eps_mode, args.eps, args.eps_min, args.eps_max)
        noisy = add_noise(raw, eps_arr, rng)
        # Assemble output fields: noisy TM channels plus unchanged fields.
        if args.keep_fields == 'slim':
            mdict = {k: noisy[k] for k in NOISE_FIELD_ORDER}
            mdict['sig_k'] = raw['sig_k']
            mdict['freq'] = raw['freq']
            mdict['obs'] = raw['obs']
        else:
            mdict = dict(raw)
            for k in NOISE_FIELD_ORDER:
                mdict[k] = noisy[k]
        print(f'[{split}] Saving (uncompressed to preserve source-like read speed)...')
        scipy.io.savemat(out_path, mdict, do_compression=False)
        print(f'[{split}] Verification:')
        verify_split(raw, noisy, mdict, eps_arr)
        if args.plot_sample is not None and split == args.plot_split:
            if 0 <= args.plot_sample < n_samples:
                plot_sample_compare(out_path, raw, noisy, eps_arr, args.plot_sample)
            else:
                print(f'    Sample index {args.plot_sample} outside 0-{n_samples - 1}; skipping plot')
        print(f'[{split}] Completed in {time.time() - t0:.1f}s')

    print('=' * 72)
    print('All done')

if __name__ == '__main__':
    main()
